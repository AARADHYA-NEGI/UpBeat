// Standalone Client Engine for UpBeat (Android APK & Mobile PWA mode when away from Mac backend)

const MODEL_ALIASES = {
  'gemini-4-argon': 'gemini-robotics-er-2-preview',
  'gemini-er-2-flash': 'gemini-robotics-er-2-preview'
}

const LOW_THINKING_MODELS = new Set(['gemini-3.8-flash', 'gemini-3.7-flash'])
const ZERO_BUDGET_MODELS = new Set(['gemini-2.5-flash', 'gemini-robotics-er-2-preview'])

export function getStoredApiKey() {
  return localStorage.getItem('upbeat_gemini_api_key') || ''
}

export function setStoredApiKey(key) {
  localStorage.setItem('upbeat_gemini_api_key', (key || '').trim())
}

export function getStoredServerUrl() {
  return (localStorage.getItem('upbeat_server_url') || '').replace(/\/+$/, '')
}

export function setStoredServerUrl(url) {
  localStorage.setItem('upbeat_server_url', (url || '').trim().replace(/\/+$/, ''))
}

export function getApiBase() {
  const custom = getStoredServerUrl()
  return custom ? `${custom}/api` : '/api'
}

function cleanJsonText(raw) {
  let s = (raw || '').trim()
  if (s.startsWith('```json')) s = s.slice(7)
  else if (s.startsWith('```')) s = s.slice(3)
  if (s.endsWith('```')) s = s.slice(0, -3)
  return JSON.parse(s.trim())
}

async function callGeminiDirect(modelId, prompt, apiKey) {
  const endpoint = MODEL_ALIASES[modelId] || modelId
  const url = `https://generativelanguage.googleapis.com/v1beta/models/${endpoint}:generateContent?key=${encodeURIComponent(apiKey)}`

  const generationConfig = { temperature: 0.55 }
  if (!endpoint.includes('gemma')) {
    generationConfig.responseMimeType = 'application/json'
  }
  if (ZERO_BUDGET_MODELS.has(endpoint) || endpoint.includes('2.5-flash')) {
    generationConfig.thinkingConfig = { thinkingBudget: 0 }
  } else if (LOW_THINKING_MODELS.has(endpoint)) {
    generationConfig.thinkingConfig = { thinkingLevel: 'LOW' }
  } else if (endpoint.includes('gemini-3') || endpoint.includes('flash-lite') || endpoint.includes('gemma-4')) {
    generationConfig.thinkingConfig = { thinkingLevel: 'MINIMAL' }
  }

  const resp = await fetch(url, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({
      contents: [{ parts: [{ text: prompt }] }],
      generationConfig
    })
  })

  if (!resp.ok) {
    throw new Error(`HTTP ${resp.status} on ${modelId}`)
  }

  const body = await resp.json()
  const parts = body?.candidates?.[0]?.content?.parts || []
  let text = ''
  for (const p of parts) {
    if (p.text && !p.thought) text += p.text
  }
  if (!text && parts.length > 0) text = parts[parts.length - 1].text || ''

  let parsed = cleanJsonText(text)
  if (Array.isArray(parsed)) parsed = { tracks: parsed }
  parsed.used_model = modelId
  return parsed
}

export async function generateWithDirectGemini(prompt, preferredModel = 'gemini-3.8-flash') {
  const apiKey = getStoredApiKey()
  if (!apiKey) {
    throw new Error('Mobile Standalone Mode requires a Gemini API Key. Tap the Key icon in the top bar to add your Gemini API Key or Mac Server URL.')
  }

  const pool = [
    preferredModel,
    'gemini-3.8-flash',
    'gemini-3.1-flash-lite',
    'gemini-4-argon',
    'gemini-3.5-flash-lite',
    'gemini-flash-lite-latest',
    'gemini-3-flash-preview',
    'gemini-2.5-flash',
    'gemma-4-26b-a4b-it'
  ]
  const seen = new Set()
  const candidates = []
  for (const m of pool) {
    const ep = MODEL_ALIASES[m] || m
    if (!seen.has(ep)) {
      seen.add(ep)
      candidates.push(m)
    }
  }

  const attempts = []
  let primaryReason = ''

  for (let i = 0; i < candidates.length; i++) {
    const m = candidates[i]
    const t0 = performance.now()
    try {
      const res = await callGeminiDirect(m, prompt, apiKey)
      const latency = Math.round(performance.now() - t0)
      attempts.push({ model: m, status: 'ok', latency_ms: latency })
      res.requested_model = preferredModel
      res.used_model = m
      res.is_fallback = i > 0
      res.latency_ms = latency
      res.model_attempts = attempts
      res.fallback_reason = i > 0 ? primaryReason : ''
      res.fallback_note = i > 0 ? `${primaryReason} -> generated by ${m}` : ''
      return res
    } catch (err) {
      const latency = Math.round(performance.now() - t0)
      const reason = err.message || `Error on ${m}`
      attempts.push({ model: m, status: 'error', reason, latency_ms: latency })
      if (i === 0) primaryReason = reason
    }
  }

  throw new Error(`All Gemini models failed (${primaryReason})`)
}

const PIPED_INSTANCES = [
  'https://pipedapi.kavin.rocks',
  'https://pipedapi.tokhmi.xyz',
  'https://pipedapi.moomoo.me'
]

function formatSeconds(sec) {
  if (!sec || sec <= 0) return '3:45'
  const m = Math.floor(sec / 60)
  const s = Math.floor(sec % 60)
  return `${m}:${s < 10 ? '0' : ''}${s}`
}

export async function searchYouTubeStandalone(query) {
  for (const base of PIPED_INSTANCES) {
    try {
      const controller = new AbortController()
      const timer = setTimeout(() => controller.abort(), 3500)
      const resp = await fetch(`${base}/search?q=${encodeURIComponent(query)}&filter=music_songs`, {
        signal: controller.signal
      })
      clearTimeout(timer)
      if (!resp.ok) continue
      const data = await resp.json()
      const items = (data?.items || []).filter((it) => it.url && it.url.includes('v='))
      if (items.length > 0) {
        const vids = items.map((it) => it.url.split('v=')[1]?.slice(0, 11)).filter(Boolean)
        const vid = vids[0]
        const dur = formatSeconds(items[0].duration)
        return {
          video_id: vid,
          fallback_ids: vids.slice(1, 5),
          duration_text: dur,
          thumbnail: `https://i.ytimg.com/vi/${vid}/hqdefault.jpg`,
          url: `https://www.youtube.com/watch?v=${vid}`,
          embed_url: `https://www.youtube.com/embed/${vid}?autoplay=1&enablejsapi=1`
        }
      }
    } catch {
      // try next instance
    }
  }
  return null
}

export async function curateStandalone({ mood_prompt, energy_level = 78, count = 8, model_name = 'gemini-3.8-flash' }) {
  const prompt = `You are an expert musicologist and playlist curator for UpBeat.

User Request:
- Prompt: "${mood_prompt}"
- Target Intensity: ${energy_level}/100
- Track Count: ${count}

STRICT RULES:
1. If the prompt names a specific anime, movie, game, franchise, or artist (e.g. "monogatari bests", "ramayan movie song", "attack on titan"), 100% of tracks MUST belong directly to that exact franchise/artist. Never mix unrelated shows.
2. Explain the musical connection in 8 to 13 words (instrumentation, vocals, rhythm, atmosphere). NEVER write meta-talk like "appealing to the user's interest".
3. If you know the official 11-character YouTube video_id for the track, include it in "known_video_id" (otherwise leave empty "").

Return ONLY a valid JSON object:
{
  "playlist_title": "string",
  "subtitle": "string",
  "vibe_description": "string",
  "tracks": [
    {
      "title": "string",
      "artist": "string",
      "search_query": "string",
      "match_tier": "Direct Match | Close Fit | Exploratory",
      "reason": "string (8-13 word musical description)",
      "detail": "string (1 sentence deeper musical note)",
      "vibe": "string (1-2 word style tag)",
      "duration_text": "string (e.g. '4:16')",
      "energy": 78
    }
  ]
}`

  const res = await generateWithDirectGemini(prompt, model_name)
  const tracks = Array.isArray(res.tracks) ? res.tracks : []

  const resolved = await Promise.all(
    tracks.map(async (t) => {
      const q = t.search_query || `${t.title} ${t.artist}`
      const found = await searchYouTubeStandalone(q)
      if (found) {
        return {
          ...t,
          video_id: found.video_id,
          fallback_ids: found.fallback_ids,
          thumbnail: found.thumbnail,
          duration_text: found.duration_text || t.duration_text || '3:50',
          url: found.url
        }
      }
      return {
        ...t,
        duration_text: t.duration_text || '3:50',
        url: `https://www.youtube.com/results?search_query=${encodeURIComponent(q)}`
      }
    })
  )

  res.tracks = resolved
  return res
}
